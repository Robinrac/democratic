import { signInWorkshopOneHost } from './workshop-one-host.mjs';
import { associations } from '../../workshop/types.mjs';
import { test, expect } from '@playwright/test';
import { randomBytes, randomUUID } from 'node:crypto';

test('weighted voting works on phones and desktops, reconciles interrupted submissions and closes safely', async ({ browser, page: host }, info) => {
  const errors = []; host.on('pageerror', error => errors.push(error.message));
  await signInWorkshopOneHost(host);
  const response = await host.request.post('/api/host/sessions', { data: { id: randomUUID(), label: 'Weighted voting rehearsal', kind: 'rehearsal', workshopType: 'workshop-1', expiresAt: Date.now() + 86400000 } });
  const { session } = await response.json(), sid = session.id;
  await host.goto('/host?s=' + sid);
  const pages = [];
  for (const [card, width] of [[1, 390], [3, 1280], [2, 390], [4, 1280]]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    pages.push(page); page.on('pageerror', error => errors.push(error.message));
    await page.goto('/?s=' + sid);
    await page.getByLabel('Organization name').fill(associations[card - 1].name);
    await page.getByRole('button', { name: 'Join workshop', exact: true }).click();
    await expect(page.locator('#join-dialog')).not.toBeVisible();
    await expect(page.locator('#voting')).not.toBeVisible();
  }
  const [phone, desktop, blank, late] = pages;
  await expect(host.locator('#vote-leader')).toHaveText('Voting not active');
  await host.getByRole('button', { name: 'Activate voting', exact: true }).click();
  await expect(host.locator('#status')).toHaveText('Voting is now open.');
  const announcement = phone.getByRole('dialog', { name: 'You can now vote', exact: true });
  await expect(announcement).toBeVisible();
  await phone.screenshot({ path: info.outputPath('phone-voting-open.png') });
  await phone.getByRole('button', { name: 'Go to vote', exact: true }).click();
  await expect(phone.getByRole('button', { name: 'Start voting', exact: true })).toBeInViewport();
  await expect(announcement).not.toBeVisible();
  await expect(desktop.locator('#voting')).toBeVisible();
  await expect(desktop.locator('#voting-open-dialog')).not.toBeVisible();
  await phone.getByRole('button', { name: 'Start voting', exact: true }).click();
  const ballot = phone.getByRole('dialog', { name: 'Cast your organization’s vote', exact: true });
  await expect(ballot).toContainText('180 members');
  await expect(ballot).toContainText('80%');
  await ballot.getByLabel('For', { exact: true }).check();
  await phone.screenshot({ path: info.outputPath('phone-ballot.png') });
  // A request that never reaches the server must remain retryable after reload.
  await phone.route('**/api/votes?*', route => route.abort('failed'));
  await ballot.getByRole('button', { name: 'Submit vote', exact: true }).click();
  await expect(ballot.getByRole('button', { name: 'Retry vote', exact: true })).toBeEnabled();
  await phone.reload();
  await expect(phone.getByRole('button', { name: 'Continue voting', exact: true })).toBeVisible();
  await phone.getByRole('button', { name: 'Continue voting', exact: true }).click();
  await expect(ballot.getByLabel('For', { exact: true })).toBeChecked();
  await expect(ballot.getByLabel('Against', { exact: true })).toBeDisabled();
  await phone.unroute('**/api/votes?*');
  await ballot.getByRole('button', { name: 'Retry vote', exact: true }).click();
  const thanks = phone.getByRole('dialog', { name: 'Thank you for your vote', exact: true });
  await expect(thanks).toContainText('180 members');
  await phone.screenshot({ path: info.outputPath('phone-vote-thanks.png') });
  await thanks.getByRole('button', { name: 'Back to feed', exact: true }).click();
  await expect(phone.locator('#news')).toBeFocused();
  await expect(phone.locator('#vote-state')).toHaveText('Vote recorded: For.');
  await phone.reload(); await expect(phone.locator('#vote-state')).toHaveText('Vote recorded: For.');
  await expect(phone.locator('#start-voting')).not.toBeVisible();
  await desktop.getByRole('button', { name: 'Start voting', exact: true }).click();
  await desktop.getByLabel('Against', { exact: true }).check();
  await desktop.getByRole('button', { name: 'Submit vote', exact: true }).click();
  await expect(desktop.locator('#vote-thanks-copy')).toContainText('350 members');
  await desktop.getByRole('button', { name: 'Back to feed', exact: true }).click();
  await blank.getByRole('button', { name: 'Go to vote', exact: true }).click();
  await blank.getByRole('button', { name: 'Start voting', exact: true }).click();
  await blank.getByLabel('Vote blank', { exact: true }).check();
  // The vote commits, but its response is lost. Reconnect must find the receipt.
  await blank.route('**/api/me?*', route => route.abort('failed'));
  await blank.route('**/api/votes?*', async route => { await route.fetch(); await route.abort('failed'); });
  await blank.getByRole('button', { name: 'Submit vote', exact: true }).click();
  await expect(blank.getByRole('button', { name: 'Retry vote', exact: true })).toBeEnabled();
  await blank.unroute('**/api/me?*'); await blank.unroute('**/api/votes?*');
  await blank.reload();
  await expect(blank.locator('#vote-thanks-copy')).toContainText('Your vote: Blank. You have voted on behalf of your 240 members.');
  await blank.getByRole('button', { name: 'Back to feed', exact: true }).click();
  await host.getByRole('button', { name: 'Refresh state', exact: true }).click();
  await expect(host.locator('#vote-leader')).toHaveText('Against leads');
  await expect(host.locator('#total-for')).toHaveText('180');
  await expect(host.locator('#total-against')).toHaveText('350');
  await expect(host.locator('#total-blank')).toHaveText('240');
  await expect(host.locator('#vote-turnout')).toContainText('770 / 1440 members represented');
  await expect(host.locator('[data-vote-card="2"]')).toContainText('Blank');
  await expect(host.locator('[data-vote-card="4"]')).toContainText('Not voted');
  await expect(host.locator('[data-vote-card="5"]')).toContainText('Not joined');
  const sportsRow = host.locator('[data-vote-card="3"]');
  await sportsRow.getByRole('button', { name: 'Does not count', exact: true }).click();
  await expect(host.locator('#vote-leader')).toHaveText('For leads');
  await expect(host.locator('#vote-counting')).toContainText('350 excluded');
  await expect(desktop.locator('#vote-state')).toContainText('does not count');
  await sportsRow.getByRole('button', { name: 'Count vote', exact: true }).click();
  await expect(host.locator('#vote-leader')).toHaveText('Against leads');
  await expect(desktop.locator('#vote-state')).toHaveText('Vote recorded: Against.');
  const creativeRow = host.locator('[data-vote-card="1"]');
  await creativeRow.getByRole('button', { name: 'Delete vote', exact: true }).click();
  await host.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(host.locator('#total-for')).toHaveText('180');
  await creativeRow.getByRole('button', { name: 'Delete vote', exact: true }).click();
  await host.getByRole('dialog', { name: 'Delete organization vote', exact: true }).getByRole('button', { name: 'Delete vote', exact: true }).click();
  await expect(host.locator('#total-for')).toHaveText('0');
  await expect(creativeRow).toContainText('Vote deleted');
  await expect(phone.locator('#vote-state')).toHaveText('The host deleted your vote. You can vote again.');
  await phone.getByRole('button', { name: 'Start voting', exact: true }).click();
  await phone.getByLabel('For', { exact: true }).check();
  await phone.getByRole('button', { name: 'Submit vote', exact: true }).click();
  await expect(phone.locator('#vote-thanks-copy')).toContainText('180 members');
  await phone.getByRole('button', { name: 'Back to feed', exact: true }).click();
  await expect(host.locator('#total-for')).toHaveText('180');
  await expect(host.locator('#vote-history')).toContainText('Host vote changes (3)');
  await host.locator('.voting-panel').screenshot({ path: info.outputPath('host-weighted-results.png') });
  await desktop.screenshot({ path: info.outputPath('desktop-vote-recorded.png'), fullPage: true });
  await late.getByRole('button', { name: 'Start voting', exact: true }).click();
  await late.getByLabel('For', { exact: true }).check();
  await host.getByRole('button', { name: 'Close voting', exact: true }).click();
  await host.getByRole('button', { name: 'Confirm release', exact: true }).click();
  await expect(late.getByRole('button', { name: 'Submit vote', exact: true })).toBeDisabled();
  await expect(late.locator('#ballot-error')).toHaveText('Voting has closed.');
  await late.getByRole('button', { name: 'Back', exact: true }).click();
  await host.reload(); await expect(host.locator('#vote-leader')).toHaveText('Against leads');
  for (const page of [host, ...pages]) expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(phone.locator('body')).not.toContainText('The Local Sports Alliance');
  await expect(phone.locator('#news .news-card')).toHaveCount(8);
  expect(errors).toEqual([]);
  for (const page of pages) await page.close();
});

test('host reveals the final weighted result to participants and projector', async ({ browser, page: host }) => {
  await signInWorkshopOneHost(host);
  const response = await host.request.post('/api/host/sessions', { data: { id: randomUUID(), label: 'Result reveal rehearsal', kind: 'rehearsal', workshopType: 'workshop-1', expiresAt: Date.now() + 86400000 } });
  const { session } = await response.json(), sid = session.id;
  const participant = await browser.newPage({ viewport: { width: 390, height: 850 }, reducedMotion: 'reduce' });
  const projector = await browser.newPage();
  await host.goto('/host?s=' + sid);
  await participant.goto('/?s=' + sid);
  await participant.getByLabel('Organization name').fill(associations[0].name);
  await participant.getByRole('button', { name: 'Join workshop', exact: true }).click();
  await expect(participant.locator('#join-dialog')).not.toBeVisible();
  await projector.goto('/?s=' + sid + '&presenter=1');
  await host.getByRole('button', { name: 'Activate voting', exact: true }).click();
  await expect(host.getByRole('button', { name: 'Reveal result to everyone' })).toBeDisabled();
  const choices = ['for', 'blank', 'against', 'blank', 'blank', 'for'];
  for (let card = 1; card <= 6; card++) {
    let token;
    if (card === 1) token = await participant.evaluate(id => localStorage.getItem('open-circle:' + id), sid);
    else {
      token = randomBytes(32).toString('hex');
      const joined = await host.request.post('/api/join?s=' + sid, { headers: { Authorization: 'Bearer ' + token }, data: { name: associations[card - 1].name } });
      expect(joined.status()).toBe(200);
    }
    const own = await host.request.get('/api/me?s=' + sid, { headers: { Authorization: 'Bearer ' + token } });
    const profile = await own.json();
    const ballot = await host.request.post('/api/votes?s=' + sid, { headers: { Authorization: 'Bearer ' + token }, data: { requestId: randomUUID(), votingId: profile.voting.id, choice: choices[card - 1] } });
    expect(ballot.status()).toBe(200);
  }
  await host.getByRole('button', { name: 'Refresh state', exact: true }).click();
  await expect(host.locator('#vote-leader')).toHaveText('Against leads');
  await expect(participant.locator('#vote-result')).not.toBeVisible();
  await expect(projector.locator('#projector-result')).not.toBeVisible();
  await host.getByRole('button', { name: 'Close voting', exact: true }).click();
  await host.getByRole('button', { name: 'Confirm release', exact: true }).click();
  await expect(host.getByRole('button', { name: 'Reveal result to everyone' })).toBeEnabled();
  await host.getByRole('button', { name: 'Reveal result to everyone' }).click();
  await expect(host.getByRole('dialog', { name: 'Reveal result' })).toContainText('Against wins');
  await host.getByRole('button', { name: 'Confirm release', exact: true }).click();
  await expect(host.locator('#reveal-status')).toContainText('Result revealed to every participant');
  await expect(participant.getByRole('dialog', { name: 'Against wins' })).toBeVisible();
  await expect(participant.locator('#vote-result')).toContainText('For 340 · Against 350 · Blank 750');
  await expect(projector.locator('#projector-result')).toContainText('Against wins');
  await participant.getByRole('button', { name: 'Back to news feed', exact: true }).click();
  await participant.reload();
  await expect(participant.locator('#vote-result')).toContainText('Against wins');
  await expect(participant.locator('#vote-result-dialog')).not.toBeVisible();
  await projector.reload();
  await expect(projector.locator('#projector-result')).toContainText('Against wins');
  await participant.close(); await projector.close();
});
