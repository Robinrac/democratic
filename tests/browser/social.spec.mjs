import { test, expect } from '@playwright/test';
import { randomUUID, randomBytes } from 'node:crypto';
import { transportCards } from '../../workshop/transport.mjs';

test('name errors, mentions, post alerts, ranked tags and reset work together on desktop and phone', async ({ browser, request, page: host }, info) => {
  const errors = []; host.on('pageerror', e => errors.push(e.message));
  await request.post('/api/host/login', { data: { password: 'browser-test-host-password-only' } });
  const sid = randomUUID(), label = 'Social tools rehearsal';
  await request.post('/api/host/sessions', { data: { id: sid, label, kind: 'rehearsal', expiresAt: Date.now() + 86400000 } });
  const tokens = [], members = [];
  for (let i = 1; i < 7; i++) {
    tokens[i] = randomBytes(32).toString('hex'); const c = transportCards[i];
    const r = await request.post('/api/join?s=' + sid, { headers: { Authorization: 'Bearer ' + tokens[i] }, data: { name: c.fullName, town: c.town, bio: c.suggestedBio, color: i, cover: i } });
    members[i] = (await r.json()).participant;
  }
  const aContext = await browser.newContext({ viewport: { width: 1280, height: 1000 }, reducedMotion: 'reduce' });
  const bContext = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  await bContext.addInitScript(({ sid, token }) => localStorage.setItem('open-circle:' + sid, token), { sid, token: tokens[1] });
  const a = await aContext.newPage(), b = await bContext.newPage();
  for (const p of [a, b]) p.on('pageerror', e => errors.push(e.message));
  await a.goto('/?s=' + sid); await b.goto('/?s=' + sid);
  const join = a.locator('#join-dialog');
  await join.getByLabel('Home town', { exact: true }).fill('Reykjavík');
  await join.getByLabel('Name', { exact: true }).fill('Someone Unknown');
  await expect(join.locator('#join-error')).toContainText('Name not recognised');
  await join.getByRole('button', { name: 'Join the forum' }).click();
  await expect(join).toBeVisible();
  await expect(join.locator('#join-error')).toContainText('Name not recognised');
  await join.getByLabel('Name', { exact: true }).fill('Eydis J');
  await expect(join.locator('#join-error')).toContainText('Name not recognised');
  await join.getByLabel('Name', { exact: true }).fill('Eydis Jonsdottir');
  await expect(join.locator('#join-error')).toBeEmpty();
  await join.getByRole('button', { name: 'Join the forum' }).click();
  await expect(join).not.toBeVisible();
  await expect(a.locator('#trending')).toContainText('1#AffordableJourneys');
  await expect(a.locator('#trending')).toContainText('0 posts · Starter');
  await expect(a.locator('#mention-person')).toHaveCount(0);
  await expect(a.getByRole('link', { name: 'My profile', exact: true })).toHaveCount(0);
  await expect(a.locator('#trending li')).toHaveCount(5);
  await expect(a.locator('#team > .sidebar-names li')).toHaveCount(7);
  await expect(a.locator('#team > .sidebar-names img, #team > .profile-banner, #team > .sidebar-bio')).toHaveCount(0);
  await expect(a.locator('.sidebar #trending')).toHaveCount(1);
  const desktopTrends = await a.locator('#trending').boundingBox();
  const desktopFeed = await a.locator('#feed-view').boundingBox();
  expect(desktopTrends.x + desktopTrends.width).toBeLessThan(desktopFeed.x);
  await a.getByRole('link', { name: 'Discover', exact: true }).click();
  await expect(a.locator('#feed-view')).toBeHidden();
  await expect(a.locator('#profiles .member-card')).toHaveCount(6);
  await expect(a.locator('#profiles')).not.toContainText('@quiet-cedar');
  await a.reload();
  await expect(a.locator('#discover-view')).toBeVisible();
  await a.screenshot({ path: info.outputPath('discover-desktop.png') });
  await b.getByRole('link', { name: 'Discover', exact: true }).click();
  await expect(b.locator('#profiles .member-card')).toHaveCount(6);
  const phoneTrends = await b.locator('#trending').boundingBox();
  const phoneDiscover = await b.locator('#discover-view').boundingBox();
  expect(phoneTrends.y).toBeGreaterThanOrEqual(phoneDiscover.y + phoneDiscover.height);
  await b.screenshot({ path: info.outputPath('discover-phone.png') });
  await a.getByRole('link', { name: 'Feed', exact: true }).click();
  await b.getByRole('link', { name: 'Feed', exact: true }).click();
  await expect(a.locator('#discover-view')).toBeHidden();
  async function release(action) {
    const state = await (await request.get('/api/host/state?s=' + sid)).json();
    const r = await request.post('/api/host/action?s=' + sid, { data: { action, version: state.version, requestId: randomUUID() } });
    expect(r.ok()).toBeTruthy();
  }
  await release('debate');
  await a.getByLabel('Lower youth fares, including free travel', { exact: true }).check();
  await a.getByLabel('Your reason or reply').fill('Would cheaper travel help @');
  await expect(a.getByRole('listbox', { name: 'Members to tag' })).toBeVisible();
  await expect(a.locator('#mention-suggestions [role=option]')).toHaveCount(7);
  await a.screenshot({ path: info.outputPath('mention-menu-desktop.png') });
  await a.getByLabel('Your reason or reply').press('Escape');
  await expect(a.locator('#mention-suggestions')).toBeHidden();
  await a.getByLabel('Your reason or reply').fill('Would cheaper travel help @b');
  await expect(a.locator('#mention-suggestions [role=option]')).toHaveCount(1);
  await a.getByLabel('Your reason or reply').press('ArrowDown');
  await a.getByLabel('Your reason or reply').press('Enter');
  await expect(a.getByLabel('Your reason or reply')).toHaveValue('Would cheaper travel help @bright-river ');
  await a.getByLabel('Your reason or reply').pressSequentially('#AffordableJourneys');
  const text = await a.getByLabel('Your reason or reply').inputValue();
  await a.getByRole('button', { name: 'Publish post' }).click();
  await expect(a.locator('#post-toast')).toContainText('You have created this post');
  await expect(a.locator('#post-toast')).toContainText(text.trim());
  await expect(b.locator('#post-toast')).toContainText('@quiet-cedar tagged you');
  await expect(a.locator('#trending li').first()).toContainText('1 post');
  await a.screenshot({ path: info.outputPath('social-desktop.png') });
  await b.screenshot({ path: info.outputPath('mention-phone.png') });
  await b.getByRole('button', { name: 'Dismiss notification' }).click();
  await b.getByRole('button', { name: 'Open your profile', exact: true }).click();
  await expect(b.locator('#member-dialog')).toContainText('Tagged posts · 1');
  await expect(b.locator('#member-dialog .tagged-post')).toContainText(text.trim());
  await b.locator('#member-dialog .tagged-post').getByRole('button', { name: 'View conversation' }).click();
  await b.locator('#threads').getByRole('button', { name: 'Reply', exact: true }).click();
  await b.getByLabel('Your reason or reply').fill('@');
  await expect(b.locator('#mention-suggestions [role=option]')).toHaveCount(7);
  await b.locator('#mention-suggestions').scrollIntoViewIfNeeded();
  await b.screenshot({ path: info.outputPath('mention-menu-phone.png') });
  await b.getByRole('option', { name: '@quiet-cedar', exact: true }).click();
  await expect(b.getByLabel('Your reason or reply')).toHaveValue('@quiet-cedar ');
  await b.getByLabel('Your reason or reply').fill('What about later buses? @quiet-cedar #ServiceFirst');
  if (await a.locator('#post-toast').isVisible()) await a.getByRole('button', { name: 'Dismiss notification' }).click();
  await b.getByRole('button', { name: 'Publish post' }).click();
  await expect(a.locator('#post-toast')).toContainText('@bright-river tagged you');
  await expect(a.locator('#post-toast')).toContainText('What about later buses?');
  await a.reload();
  await expect(a.locator('#activity-history')).toContainText('Activity · 2');
  await expect(a.locator('#post-toast')).not.toBeVisible();
  await a.locator('#trending [data-hashtag="servicefirst"]').click();
  await expect(a.locator('#tag-filter')).toContainText('#servicefirst');
  await expect(a.locator('#threads .post')).toHaveCount(1);
  await a.getByRole('button', { name: 'Show all posts' }).click();
  await expect(a.locator('#threads .post')).toHaveCount(2);
  for (let i = 1; i < 7; i++) await request.post('/api/posts?s=' + sid, { headers: { Authorization: 'Bearer ' + tokens[i] }, data: { text: transportCards[i].suggestedPost, stance: transportCards[i].leaning, requestId: randomUUID() } });
  await release('incident');
  await expect(a.getByRole('dialog', { name: 'Your account is locked' })).toBeVisible();
  await expect(b.getByRole('dialog', { name: 'Support is arriving' })).toBeVisible();
  await b.getByRole('button', { name: 'Back to the feed' }).click();
  await b.getByRole('button', { name: 'Open your profile', exact: true }).click();
  await expect(b.locator('#member-dialog')).toContainText('Tagged posts · 0');
  await host.goto('/host?s=' + sid);
  await host.getByLabel('Password', { exact: true }).fill('browser-test-host-password-only');
  await host.getByRole('button', { name: 'Unlock host screen' }).click();
  await host.getByText('Rehearsal reset, export and clear', { exact: true }).click();
  host.once('dialog', dialog => dialog.accept(label));
  await host.getByRole('button', { name: 'Reset this rehearsal', exact: true }).click();
  await expect(host.locator('#status')).toContainText('Rehearsal reset');
  for (const p of [a, b]) {
    await expect(p.locator('#join-dialog')).toBeVisible();
    await expect(p.locator('#incident-dialog')).not.toBeVisible();
    await expect(p.locator('#member-dialog')).not.toBeVisible();
    await expect(p.locator('#post-toast')).not.toBeVisible();
    await expect(p.locator('#threads')).toBeEmpty();
  }
  await expect(a.locator('#join-name')).toHaveValue('');
  await a.locator('#join-name').fill('Eydis'); await a.locator('#join-town').fill('Reykjavík');
  await a.getByRole('button', { name: 'Join the forum' }).click();
  await expect(a.locator('#join-dialog')).not.toBeVisible();
  await expect(a.locator('#incident-banner')).toBeEmpty();
  await expect(a.locator('#trending li').first()).toContainText('0 posts');
  expect(errors).toEqual([]);
  await aContext.close(); await bContext.close();
});
