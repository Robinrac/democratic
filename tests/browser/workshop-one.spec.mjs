  await expect(join).not.toBeVisible();
  const other = await browser.newPage(); await other.goto('/?s=' + sid);
  // An old preview response must not replace the currently typed organization.
  let received, release;
  const intercepted = new Promise(resolve => { received = resolve; });
  const blocked = new Promise(resolve => { release = resolve; });
  await other.route('**/api/join-preview?*', async route => {
    if (route.request().postDataJSON().name === 'Creative') {
      const response = await route.fetch(); received(); await blocked; await route.fulfill({ response });
    } else await route.continue();
  });
  await other.getByLabel('Organization name').fill('Creative'); await intercepted;
  await other.getByLabel('Organization name').fill('Gaming');
  await expect(other.locator('#join-preview')).toContainText('The Gaming & Tech Society');
  release(); await other.unrouteAll({ behavior: 'wait' });
  await expect(other.locator('#join-preview')).toContainText('The Gaming & Tech Society');
  await other.getByLabel('Organization name').fill('Unknown organization');
  await expect(other.locator('#join-preview')).not.toBeVisible();
  await other.getByLabel('Organization name').fill('The Creative & Cultural Collective');
  await other.getByRole('button', { name: 'Join workshop', exact: true }).click();
  await expect(other.locator('#join-error')).toContainText('already joined');
  await other.getByLabel('Organization name').fill('The Suburban & Rural Youth Network');
  await other.getByRole('button', { name: 'Join workshop', exact: true }).click();
  await expect(other.locator('#team')).toContainText('The Suburban & Rural Youth Network');
  await expect(other.locator('.news-card').first()).toContainText('The same last bus home');
  await expect(other.locator('#news')).not.toContainText('Their rehearsal ends');
