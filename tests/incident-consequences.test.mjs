import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { workshop, secret } from './helpers.mjs';
import { transportCards } from '../workshop/transport.mjs';

test('exposure is immediately followed by a tagged portrait; deletion revokes access and reserves a genuinely new account', async t => {
  const w = await workshop(t); await w.login();
  const { sid } = await w.session('rehearsal', 'transport-v1');
  const teams = []; for (let i = 0; i < 7; i++) teams.push(await w.claim(sid, i));
  const mats = teams[6], viewer = secret();
  await w.call('viewer', { token: viewer }, { sid, token: mats.token });
  await w.action(sid, 'debate');
  for (const [i, card] of transportCards.entries()) await w.call('posts', { text: card.suggestedPost, requestId: randomUUID(), identityCard: 5 }, { sid, token: teams[i].token });
  const before = await w.call('feed', undefined, { sid, token: teams[4].token });
  assert.ok(before.posts.every(p => !p.exposedIdentity));
  assert.equal(before.trending[0].tag, 'affordablejourneys');
  await w.action(sid, 'incident');
  const after = await w.call('feed', undefined, { sid, token: teams[4].token });
  const reaction = after.posts.find(p => p.exposedIdentity);
  assert.equal(reaction.author.username, 'fare-watch');
  assert.deepEqual(reaction.mentions, [teams[4].participant.id]);
  assert.equal(reaction.exposedIdentity.portrait, '/portraits/5.png');
  assert.match(reaction.text, /parents and friends/);
  const stored = await w.server.store.read(sid), scripted = stored.posts.filter(p => p.origin === 'simulation');
  assert.equal(reaction.replyTo, scripted[2].id); assert.equal(scripted[3].id, reaction.id);
  assert.equal(after.trending[0].tag, 'servicefirst');
  assert.equal(after.trending[0].count, 10);
  assert.ok(after.activity.find(a => a.postId === reaction.id).exposedIdentity);
  assert.equal((await w.call('me', undefined, { sid, token: mats.token })).canWrite, false);
  assert.equal((await w.call('posts', { text: 'Should be blocked', requestId: randomUUID() }, { sid, token: mats.token })).status, 403);
  const newToken = secret(), body = { newToken };
  assert.equal((await w.call('restart-account', body, { sid, token: teams[2].token })).status, 409);
  assert.equal((await w.call('restart-account', body, { sid, token: mats.token })).status, 200);
  assert.equal((await w.call('restart-account', body, { sid, token: mats.token })).status, 200); // lost-response retry
  for (const token of [mats.token, viewer]) assert.equal((await w.call('me', undefined, { sid, token })).status, 401);
  const profile = { name: 'Mats Berg', town: 'Tromsø', bio: 'Starting again', color: 6, cover: 6 };
  assert.notEqual((await w.call('join', profile, { sid, token: secret() })).status, 200);
  const joined = await w.call('join', profile, { sid, token: newToken });
  assert.equal(joined.status, 200); assert.equal(joined.canWrite, true);
  assert.notEqual(joined.participant.id, mats.participant.id);
  assert.equal(joined.participant.username, 'nordlys-vandrer-ny');
  assert.equal((await w.call('posts', { text: 'I am back. #AffordableJourneys', requestId: randomUUID() }, { sid, token: newToken })).status, 200);
  const exported = await w.call('host/export', undefined, { sid, host: true });
  assert.equal(exported.replacements, undefined); assert.ok(exported.roles.every(r => r.rejoinHash === undefined));
  await w.action(sid, 'reflection'); await w.action(sid, 'reveal');
  const restored = await w.call('feed', undefined, { sid, token: newToken });
  assert.ok(restored.posts.some(p => p.author.id === mats.participant.id && p.author.username === 'nordlys-vandrer'));
  assert.equal(restored.posts.filter(p => p.author.id === joined.participant.id).length, 1);
  const host = await w.state(sid); assert.equal(host.roles[6].activity.posts, 2); assert.equal(host.roles[6].recreated, true);
});
