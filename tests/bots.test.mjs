import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID, randomBytes } from 'node:crypto';
import { makeSession, join, me, feed, release, participantWrite, advanceIncident, incidentPending, hostView, setPaused } from '../workshop/model.mjs';
import { transportCards } from '../workshop/transport.mjs';
import { botTargets } from '../workshop/bots.mjs';

for (const card of botTargets) test(`bot campaigns target only the selected fictional profile, card ${card}, and run once`, () => {
  let state = makeSession({ id: randomUUID(), label: 'Bots', kind: 'rehearsal', expiresAt: Date.now() + 3600000 }).state;
  const tokens = transportCards.map(() => randomBytes(32).toString('hex'));
  transportCards.forEach((c, i) => join(state, { name: c.fullName, town: c.town, bio: '', color: i, cover: i }, tokens[i]));
  const action = name => release(state, { action: name, version: state.version, requestId: randomUUID() }, { incidentStepMs: 0 });
  const deploy = (i, targetId) => participantWrite(state, tokens[i], 'deploy-bots', { requestId: randomUUID(), ...(targetId ? { targetId } : {}) });
  assert.throws(() => deploy(1), { status: 409 }); action('debate');
  transportCards.forEach((c, i) => participantWrite(state, tokens[i], 'posts', { text: c.suggestedPost, requestId: randomUUID() })); action('incident');
  const target = state.roles[card - 1];
  assert.equal(me(state, tokens[1]).botControl.messages.length, 10);
  assert.ok(me(state, tokens[1]).botControl.messages.every(message => message.includes('#ExpensiveRides')));
  assert.deepEqual(me(state, tokens[3]).botControl.targets.map(p => p.id), botTargets.map(n => state.roles[n - 1].id));
  assert.throws(() => deploy(2, target.id), { status: 403 });
  assert.throws(() => deploy(3, state.roles[6].id), { status: 400 });
  assert.throws(() => deploy(1, target.id), { status: 400 });
  setPaused(state, true); assert.throws(() => deploy(1), { status: 409 }); setPaused(state, false);
  const hashtags = deploy(1), attack = deploy(3, target.id);
  assert.deepEqual(deploy(1), hashtags); assert.deepEqual(deploy(3, target.id), attack);
  assert.throws(() => deploy(3, state.roles.find(r => botTargets.includes(r.card) && r.id !== target.id).id), { status: 409 });
  assert.equal(state.incidentQueue.length, 24); assert.equal(incidentPending(state), 13);
  assert.throws(() => action('reflection'), { status: 409 });
  const start = Date.now(); setPaused(state, true, start);
  assert.equal(advanceIncident(state, start + 60000), 0);
  state = JSON.parse(JSON.stringify(state)); setPaused(state, false, start + 60000);
  advanceIncident(state, start + 120000);
  assert.equal(incidentPending(state), 0); assert.equal(state.posts.length, 31);
  const attackPosts = state.posts.filter(p => p.attackCampaign);
  assert.equal(attackPosts.length, 5); assert.equal(new Set(attackPosts.map(p => p.authorId)).size, 5);
  assert.equal(new Set(attackPosts.map(p => p.text)).size, 5);
  assert.ok(attackPosts.every(p => p.mentions.length === 1 && p.mentions[0] === target.id));
  assert.ok(attackPosts.every(p => !state.roles.some(r => r.id === p.authorId)));
  const targetFeed = feed(state, tokens[card - 1]);
  assert.equal(targetFeed.activity.filter(a => a.attackCampaign).length, 5);
  assert.equal(feed(state, tokens[1]).activity.filter(a => a.attackCampaign).length, 0);
  assert.equal(feed(state, tokens[1]).botCampaigns, undefined);
  assert.equal(me(state, tokens[1]).botControl.campaign.published, 10);
  assert.equal(me(state, tokens[3]).botControl.campaign.published, 5);
  assert.equal(hostView(state).botCampaigns.length, 2);
  assert.equal(feed(state, tokens[1]).trending[0].count, 25);
  const count = state.posts.length; advanceIncident(state, start + 180000); assert.equal(state.posts.length, count);
  action('reflection'); assert.equal(me(state, tokens[1]).botControl.allowed, false); action('reveal');
  assert.ok(feed(state, tokens[1]).posts.filter(p => p.attackCampaign).every(p => p.provenance === 'simulation'));
});
